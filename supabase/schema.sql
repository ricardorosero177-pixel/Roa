-- Esquema y seguridad de base de datos para RÖA (Supabase / PostgreSQL)
-- Ejecuta este SQL en el editor SQL de tu proyecto Supabase.

-- 1) Tabla de cotizaciones
create table if not exists public.quotes (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  email text not null,
  phone text not null,
  description text,
  items jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists quotes_created_at_idx on public.quotes (created_at desc);

-- 2) Row Level Security: bloquea todo por defecto.
alter table public.quotes enable row level security;

-- 3) Privilegios mínimos.
-- El público (clave anon) solo puede INSERTAR; nunca leer, modificar ni borrar.
revoke all on public.quotes from anon, authenticated;
grant insert on public.quotes to anon, authenticated;

-- 4) Política de inserción con validación de longitudes (defensa en profundidad).
drop policy if exists "quotes_insert_public" on public.quotes;
create policy "quotes_insert_public"
  on public.quotes
  for insert
  to anon, authenticated
  with check (
    char_length(name) between 1 and 120
    and char_length(email) between 3 and 160
    and email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'
    and char_length(coalesce(phone, '')) between 3 and 40
    and char_length(coalesce(description, '')) <= 2000
  );

-- 5) Lectura: NO se crea política de SELECT para anon/authenticated.
--    El panel /admin lee con la SERVICE ROLE (SUPABASE_SERVICE_ROLE_KEY),
--    que ignora RLS y es secreta: solo vive en el servidor, nunca en el navegador.

-- Nota: nunca expongas SUPABASE_SERVICE_ROLE_KEY en variables NEXT_PUBLIC_*.


-- 6) Tabla de pedidos (pagos de MercadoPago)
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  mp_payment_id text unique not null,
  status text not null,
  amount numeric not null default 0,
  email text,
  items jsonb not null default '[]'::jsonb,
  customer jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists orders_created_at_idx on public.orders (created_at desc);

-- RLS: nadie accede con la clave pública. El webhook y el panel usan la service role.
alter table public.orders enable row level security;
revoke all on public.orders from anon, authenticated;
-- No se crean policies para anon/authenticated: solo la service role (servidor) lee/escribe.

-- Despacho (se maneja desde el panel) y control para descontar stock una sola vez.
alter table public.orders
  add column if not exists fulfillment text not null default 'nuevo'
    check (fulfillment in ('nuevo', 'preparando', 'enviado', 'entregado')),
  add column if not exists notes text not null default '',
  add column if not exists stock_applied boolean not null default false;


-- 7) Productos (editables desde /admin)
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  price integer not null check (price >= 0),
  image text not null default '',
  category_slug text not null,
  short_description text not null default '',
  description text not null default '',
  featured boolean not null default false,
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
revoke all on public.products from anon, authenticated;

-- Descuenta stock sin bajar de cero (lo usa el webhook de MercadoPago).
create or replace function public.decrement_stock(p_id bigint, p_qty integer)
returns void
language sql
as $$
  update public.products set stock = greatest(stock - p_qty, 0) where id = p_id;
$$;
revoke all on function public.decrement_stock(bigint, integer) from public, anon, authenticated;


-- 8) Artículos del blog (editables desde /admin)
create table if not exists public.posts (
  slug text primary key,
  title text not null,
  excerpt text not null default '',
  category text not null default '',
  date date not null default current_date,
  cover text not null default '',
  reading_minutes integer not null default 3,
  content text not null default '', -- párrafos separados por una línea en blanco
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.posts enable row level security;
revoke all on public.posts from anon, authenticated;


-- 9) Reseñas de clientas (editables desde /admin)
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null,
  text text not null,
  rating integer not null default 5 check (rating between 1 and 5),
  visible boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.reviews enable row level security;
revoke all on public.reviews from anon, authenticated;


-- 10) Páginas de texto editables (política de devoluciones)
create table if not exists public.pages (
  slug text primary key,
  title text not null,
  intro text not null default '',
  content text not null,
  updated_at timestamptz not null default now()
);

alter table public.pages enable row level security;
revoke all on public.pages from anon, authenticated;


-- 11) Carpeta pública para las fotos que se suben desde el panel.
--     Cualquiera puede VER las fotos; solo el servidor (service role) puede subirlas.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('imagenes', 'imagenes', true, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;
